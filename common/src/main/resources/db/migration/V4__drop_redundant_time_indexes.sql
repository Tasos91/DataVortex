-- Δύο ευρετήρια που κόστιζαν σε κάθε εγγραφή χωρίς να εξυπηρετούν κανένα ερώτημα της εφαρμογής.
--
-- Το create_hypertable() φτιάχνει από μόνο του ένα ευρετήριο στη στήλη χρόνου. Είναι λογική
-- προεπιλογή, αλλά εδώ περισσεύει και στους δύο πίνακες:
--
--   ingested_records : το PRIMARY KEY είναι (event_time, topic, kafka_partition, kafka_offset),
--                      δηλαδή ξεκινά ΗΔΗ από το event_time. Κάθε ερώτημα εύρους χρόνου το
--                      χρησιμοποιεί εξίσου καλά.
--   metric_points    : διαβάζεται από τα συνεχή συγκεντρωτικά, που σαρώνουν ολόκληρα chunks, και
--                      από το idx_metric_points_lookup (source_id, field, event_time DESC) που
--                      καλύπτει κάθε ερώτημα της εφαρμογής — όλα φιλτράρουν ανά πηγή. Ο
--                      αποκλεισμός chunks γίνεται από τα όρια του chunk, όχι από ευρετήριο.
--
-- Μετρημένο στο ίδιο μηχάνημα, με 200.000 εγγραφές x 5 μετρικές:
--   εγγραφή μέχρι τη βάση : 17.087 ms -> 14.304 ms  (+19%)
--   μέγεθος βάσης         : 1081 MB   -> 975 MB     (-106 MB)
--   /series, /records, /api/dashboard : αμετάβλητα (1,4 ms / 2,5 ms / 5,7 ms)
--
-- Αν κάποτε χρειαστεί ερώτημα σε metric_points ΧΩΡΙΣ source_id (π.χ. "πόσα σημεία συνολικά την
-- τελευταία ώρα"), το ευρετήριο ξαναμπαίνει με ένα CREATE INDEX — δεν χάνεται τίποτα.

DROP INDEX IF EXISTS ingested_records_event_time_idx;
DROP INDEX IF EXISTS metric_points_event_time_idx;
